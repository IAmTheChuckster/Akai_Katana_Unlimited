#!/usr/bin/env python3
"""Build src/warntext.s: replacement warning-screen text for the RAM region 0x0C3042D4-0x0C3045F3.

The game keeps two warning screens (Japan: 8 slots of 40 chars, export: 13 slots of 30 chars) and the
version/date line between them. Each string is rewritten in place, padded with spaces to its original
length, so all pointers and the layout stay valid."""
import textwrap, os
MSG = ("This project is unofficial and is not affiliated with, endorsed by, or authorized by CAVE. "
       "All rights to the original game and its associated intellectual property remain with their "
       "respective rights holders.")
FUN = "HAVE FUN!!!"
DATE = "2026/10/23 UNLIMITED"
BASE = 0x3042D4
# original layout: (offset, length) of each string, read from the 2010/8/13 program
JP = [(0x3042d4+i*0x2c,40) for i in range(8)]
DT = (0x304434,28)
EX = [(0x304454+i*0x20,30) for i in range(13)]
END = 0x3045F4
def block(slots, indent, width):
    lines = textwrap.wrap(MSG, width) + [''] + [FUN]
    assert len(lines) <= len(slots), (len(lines), len(slots))
    lines += [''] * (len(slots) - len(lines))
    out = []
    for (off, n), l in zip(slots, lines):
        s = (' ' * indent + l).ljust(n)
        assert len(s) == n, s
        out.append((off, s))
    return out
strs = block(JP, 2, 36) + block(EX, 3, 25)
d = ' ' * (DT[1] - len(DATE)) ; ds = (d[:7] + DATE).ljust(DT[1]); strs.append((DT[0], ds))
mem = bytearray(END - BASE)
for off, s in strs:
    mem[off - BASE:off - BASE + len(s)] = s.encode('ascii')
# keep the NUL terminators / padding of the original: every byte not covered by a string is 0
here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, '..', 'src', 'warntext.s'), 'w') as f:
    f.write('! generated by tools/warntext.py - replacement warning text for 0x0C3042D4..0x0C3045F3\n')
    for i in range(0, len(mem), 16):
        f.write('        .byte ' + ','.join('0x%02x' % b for b in mem[i:i+16]) + '\n')
for off, s in sorted(strs): print(hex(0x0C000000 + off), repr(s))
